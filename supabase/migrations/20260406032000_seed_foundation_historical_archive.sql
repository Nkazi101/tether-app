upserted_cases as (
  insert into public.historical_cases (
    slug,
    title,
    summary,
    year_label,
    start_year,
    end_year,
    domain_slug,
    event_type_slug,
    structural_summary,
    outcome_summary,
    disanalogy_notes,
    source_quality_score,
    case_confidence_score,
    metadata
  )
  select
    slug,
    title,
    summary,
    year_label,
    start_year,
    end_year,
    domain_slug,
    event_type_slug,
    structural_summary,
    outcome_summary,
    disanalogy_notes,
    source_quality_score,
    case_confidence_score,
    jsonb_build_object(
      'seed', 'foundation-archive-v1',
      'legacy_archetype', legacy_archetype,
      'source_pack', 'foundation-canon'
    )
  from foundation_cases
  on conflict (slug) do update
  set
    title = excluded.title,
    summary = excluded.summary,
    year_label = excluded.year_label,
    start_year = excluded.start_year,
    end_year = excluded.end_year,
    domain_slug = excluded.domain_slug,
    event_type_slug = excluded.event_type_slug,
    structural_summary = excluded.structural_summary,
    outcome_summary = excluded.outcome_summary,
    disanalogy_notes = excluded.disanalogy_notes,
    source_quality_score = excluded.source_quality_score,
    case_confidence_score = excluded.case_confidence_score,
    metadata = coalesce(public.historical_cases.metadata, '{}'::jsonb) || excluded.metadata,
    updated_at = timezone('utc', now())
  returning id, slug
)
select id, slug from upserted_cases;

